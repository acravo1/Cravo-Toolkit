#!/usr/bin/env bash

###############################################################################
# CTK Library Loader
###############################################################################

CTK_LIB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CTK_LIB_D="${CTK_LIB_DIR}/lib.d"

###############################################################################
# Load all CTK modules
###############################################################################

for module in "${CTK_LIB_D}"/*.sh
do
    [[ -f "$module" ]] || continue

    source "$module"
done
