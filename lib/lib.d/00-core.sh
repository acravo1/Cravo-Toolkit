#!/usr/bin/env bash

###############################################################################
# CTK Core Functions
###############################################################################

ctk_timestamp()
{
    date -u +"%Y%m%dT%H%M%SZ"
}

###############################################################################

ctk_hostname()
{
    hostname
}

###############################################################################

ctk_user()
{
    whoami
}

###############################################################################

ctk_sha256_file()
{
    local file="$1"

    sha256sum "$file" | awk '{print $1}'
}

###############################################################################

ctk_safe_hash()
{
    local data="$*"

    printf "%s" "$data" \
        | sha256sum \
        | cut -c1-16
}
